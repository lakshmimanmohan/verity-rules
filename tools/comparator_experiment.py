"""
Comparator variant experiment (v0 to v4). Not shipped to users. Report only.

  .venv\\Scripts\\python.exe tools/comparator_experiment.py   # writes validation/comparator_experiment.md

For each dataset and variant: per column comparison method, mean similarity on 5,000 random non-duplicate
pairs, learned reliability and composite weight; AUC and best-cutoff errors against hard negatives
(customers, Copy C, Copy H, Copy H2) or AUC against random negatives only (products). Every variant is run
twice and the two reports must be identical after rounding to six decimals.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

import numpy as np
from sklearn.metrics import roc_auc_score

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(Path(__file__).resolve().parent))

from validate import Dataset, N_RANDOM_NEG, SEED, best_cutoff, table  # noqa: E402
from verity_rules.core import learn_rules  # noqa: E402
from verity_rules.rule_learner import COMPARATOR_VARIANTS, field_similarity, is_null  # noqa: E402

DATA = ROOT / "data"
CUSTOMER_SETS = [("customers", "customers.csv"), ("Copy C", "customers_degraded_C.csv"),
                 ("Copy H", "customers_degraded_H.csv"), ("Copy H2", "customers_degraded_H2.csv")]
PRODUCTS = ("products", "products.csv")


def r6(x):
    return None if x is None else round(float(x), 6)


def run_one(name: str, csv: str, truth: str, variant: str, hard: bool) -> dict:
    ds = Dataset(name, DATA / csv, DATA / truth, variant=variant)
    neg_rand = ds.random_non_dup(N_RANDOM_NEG)
    cols = {}
    for p in ds.profiles:
        sims = [field_similarity(ds.rows[i][p.name], ds.rows[j][p.name], p, ds.lo_hi[p.name],
                                 comparator_variant=variant)
                for i, j in neg_rand
                if not (is_null(ds.rows[i].get(p.name)) or is_null(ds.rows[j].get(p.name)))]
        c = ds.result["columns"][p.name]
        cols[p.name] = {"method": c["comparison_method"], "semantic_type": c["semantic_type"],
                        "mean_sim": r6(np.mean(sims)) if sims else None, "n": len(sims),
                        "reliability": c["reliability_score"], "weight": c["composite_weight"]}
    weights = {c: v["weight"] for c, v in cols.items()}
    ds.set_weights({p.name: ds.result["columns"][p.name]["composite_weight"] for p in ds.profiles})
    pos = ds.score(ds.dup_pairs)
    out = {"columns": cols, "n_pos": len(pos)}
    negs = {"random": neg_rand}
    if hard:
        negs["hard"] = ds.hard_negatives()[0]
    for k, neg in negs.items():
        ng = ds.score(neg)
        out[f"auc_{k}"] = r6(roc_auc_score([1] * len(pos) + [0] * len(ng), pos + ng))
        if k == "hard":
            out["cutoff_hard"] = best_cutoff(pos, ng)
    # full public result must also repeat exactly
    res = learn_rules(ds.records, seed=SEED, comparator_variant=variant)
    out["result_json"] = json.dumps(res, sort_keys=True)
    return out


def main() -> int:
    results: dict = {}
    identical = True
    jobs = [(n, f, "customers_truth.csv", True) for n, f in CUSTOMER_SETS] + \
           [(PRODUCTS[0], PRODUCTS[1], "products_truth.csv", False)]
    for name, csv, truth, hard in jobs:
        for v in COMPARATOR_VARIANTS:
            a = run_one(name, csv, truth, v, hard)
            b = run_one(name, csv, truth, v, hard)
            same = a == b
            identical &= same
            print(f"{name} {v}: second run {'identical' if same else 'DIFFERENT'}", flush=True)
            a.pop("result_json")
            a["repeat_identical"] = same
            results[(name, v)] = a

    L = ["# Comparator variant experiment", "",
         "Branch `exp-comparators`. Seed 42. Report only; `verity_rules/` default (`v0`) is unchanged. "
         "Generated by `tools/comparator_experiment.py`.", "",
         "Variants. **v0**: current behavior. **v1**: EMAIL and DATE checks before the IDENTIFIER check; other IDENTIFIER "
         "columns stay exact. **v2**: v1, other IDENTIFIER columns compare after lowercasing and removing every non-letter, "
         "non-digit character (exact match on the result). **v3**: v1, other IDENTIFIER columns use Jaccard of adjacent "
         "character pairs (bigrams) of the same normalized value. **v4**: v3, and text_character columns (no embeddings) use "
         "the same bigram Jaccard instead of character-set Jaccard.", "",
         "Notes. Mean similarity is over the same 5,000 random non-duplicate pairs (seed 42), pairs where both values are "
         "non-null. Learned reliability and composite weight are `learn_rules(..., comparator_variant=v)`; scoring for AUC and "
         "best cutoff uses the same variant and those weights. Hard negatives: candidate pairs that are not true duplicates "
         "(capped at 5,000). Best-cutoff errors = missed duplicates + false merges, in pairs. "
         "Bigrams: a one-character value is its own single gram; two values that normalize to nothing match only if equal as text.", "",
         f"**Repeat check: each variant on each dataset was run twice; every report and full learn_rules result was "
         f"{'identical' if identical else 'NOT identical'}.**", ""]
    for name, csv, truth, hard in jobs:
        L += [f"## {name}", ""]
        for v in COMPARATOR_VARIANTS:
            r = results[(name, v)]
            head = f"### {name}, {v}"
            if hard:
                bc = r["cutoff_hard"]
                head2 = (f"AUC vs hard negatives {r['auc_hard']:.6f}; best-cutoff errors {bc['errors']} "
                         f"(missed {bc['missed']}, false merges {bc['false_merges']}; {bc['n_pos']} duplicate pairs, "
                         f"{bc['n_neg']} hard negatives).")
            else:
                head2 = f"AUC vs random negatives {r['auc_random']:.6f} ({r['n_pos']} duplicate pairs, {N_RANDOM_NEG} random negatives)."
            L += [head, "", head2, ""]
            L += table(["Column", "Semantic type", "Comparison method", "Mean sim, random non-dups", "n", "Reliability", "Weight"],
                       [[c, d["semantic_type"], d["method"], "n/a" if d["mean_sim"] is None else f"{d['mean_sim']:.6f}",
                         d["n"], f"{d['reliability']:.6f}", f"{d['weight']:.6f}"] for c, d in r["columns"].items()])

    def col(name, v, c, key):
        d = results[(name, v)]["columns"].get(c)
        return "n/a" if d is None else f"{d[key]:.6f}"

    rows = []
    for v in COMPARATOR_VARIANTS:
        rows.append([v,
                     col("Copy H", v, "email", "reliability"), col("Copy H", v, "phone", "reliability"),
                     col("customers", v, "email", "reliability"), col("customers", v, "phone", "reliability"),
                     results[("Copy H", v)]["cutoff_hard"]["errors"], results[("Copy H2", v)]["cutoff_hard"]["errors"],
                     results[("customers", v)]["cutoff_hard"]["errors"],
                     col("products", v, "member_id", "weight"), col("products", v, "member_part_number", "weight")])
    header = ["Variant", "Copy H email rel", "Copy H phone rel", "customers email rel", "customers phone rel",
              "Errors H", "Errors H2", "Errors customers", "products member_id weight", "products member_part_number weight"]
    summary = ["## Summary", ""] + table(header, rows)
    L[L.index(f"## {CUSTOMER_SETS[0][0]}"):L.index(f"## {CUSTOMER_SETS[0][0]}")] = summary
    out = ROOT / "validation" / "comparator_experiment.md"
    out.write_text("\n".join(L), encoding="utf-8")
    print(f"wrote {out}\n")
    print("\n".join(summary))
    return 0 if identical else 1


if __name__ == "__main__":
    sys.exit(main())
