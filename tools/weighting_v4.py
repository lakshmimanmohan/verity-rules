"""
Weighting comparison under comparator v4. Not shipped to users. Report only.

  .venv/Scripts/python.exe tools/weighting_v4.py   # writes validation/weighting_v4.md

For customers and the degraded copies C, C25, H and H2: learned, equal, uniqueness-only and v1 weights, all scored
by the same code (Dataset.score -> weighted_pair_similarity, comparator_variant="v4") against the same true
duplicate pairs and the same hard negatives (candidate pairs that are not true duplicates, capped at 5,000, seed 42).
"""
from __future__ import annotations

import sys
from pathlib import Path

import numpy as np
from sklearn.metrics import roc_auc_score

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(Path(__file__).resolve().parent))

from validate import HARD_NEG_CAP, SCHEMES, SEED, Dataset, best_cutoff, table  # noqa: E402
from verity_rules.core import learn_rules  # noqa: E402

DATA = ROOT / "data"
VARIANT = "v4"
SETS = [("customers", "customers.csv"), ("Copy C", "customers_degraded_C.csv"),
        ("Copy C25", "customers_degraded_C25.csv"), ("Copy H", "customers_degraded_H.csv"),
        ("Copy H2", "customers_degraded_H2.csv")]


def section(name: str, csv: str) -> list[str]:
    ds = Dataset(name, DATA / csv, DATA / "customers_truth.csv", variant=VARIANT)
    assert ds.variant == VARIANT
    v1 = {c: v["composite_weight"] for c, v in
          learn_rules(ds.records, seed=SEED, reliability="v1", comparator_variant=VARIANT)["columns"].items()}
    learned = {c: ds.result["columns"][c]["composite_weight"] for c in ds.columns}
    schemes = ds.weight_schemes(learned, v1)
    neg, n_cand, n_all = ds.hard_negatives()
    rows = []
    for k in SCHEMES:
        ds.set_weights(schemes[k])
        pos, ng = ds.score(ds.dup_pairs), ds.score(neg)
        a = float(roc_auc_score([1] * len(pos) + [0] * len(ng), pos + ng))
        b = best_cutoff(pos, ng)
        rows.append([k, f"{a:.6f}", b["errors"], b["missed"], b["false_merges"]])
    L = [f"## {name}", "",
         f"{len(ds.dup_pairs)} true duplicate pairs; {len(neg)} hard negatives (of {n_cand} candidates, {n_all} "
         "non-duplicate" + (f"; capped at {HARD_NEG_CAP}" if n_all > HARD_NEG_CAP else "") + ").", ""]
    return L + table(["Weighting", "AUC (hard)", "Best-cutoff errors", "missed duplicates", "false merges"], rows)


def main() -> int:
    L = ["# Weighting comparison under comparator v4", "",
         "Seed 42. Report only; nothing in `verity_rules/` changed. Generated by `tools/weighting_v4.py`. Comparator "
         "`v4` for the learned weights, the v1 weights and the pair scoring. Every weighting is scored by the same code "
         "against the same pairs. Negatives are hard negatives only. Errors = missed duplicates + false merges at the "
         "best single cutoff, in pairs (ties go to the higher cutoff).", ""]
    for name, csv in SETS:
        print(name, flush=True)
        L += section(name, csv)
    out = ROOT / "validation" / "weighting_v4.md"
    out.write_text("\n".join(L), encoding="utf-8")
    print("\n".join(L))
    return 0


if __name__ == "__main__":
    sys.exit(main())
