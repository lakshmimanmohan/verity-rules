"""
Check group-aware row sampling against random sampling. Not shipped to users. Report only.

  .venv/Scripts/python.exe tools/group_sampling_check.py   # writes validation/group_sampling_results.md

1. data/customers.csv with --max-rows 400, 1000 and 2000 in both modes: max weight difference and
   Spearman rank correlation against the weights learned from all rows.
2. A 100,000-row customers file (NUM_ENTITIES 50000, TOTAL_ROWS 100000, generated by
   tools/generate_data.py, truth file kept): verity learn with --max-rows 100000 and with the default
   cap. Time, peak memory, weight difference, rank correlation and, from the truth file, the share of
   true duplicate pairs whose two rows are both in the sample.
"""
from __future__ import annotations

import sys
from collections import defaultdict
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(Path(__file__).resolve().parent))

import generate_data  # noqa: E402
import split_truth  # noqa: E402
from row_count_dependence import cli_run, compare, run, summary  # noqa: E402
from validate import table  # noqa: E402
from verity_rules.cli import DEFAULT_MAX_ROWS, read_records, sample_records  # noqa: E402

SEED = 42
DATA = ROOT / "data"
OUT = ROOT / "validation" / "group_sampling_results.md"
BIG = DATA / "customers_100k.csv"
BIG_TRUTH = DATA / "customers_100k_truth.csv"


def small_check() -> list[str]:
    records = read_records(DATA / "customers.csv")
    full = summary(run(records))
    cols = sorted(full["weights"], key=lambda c: (-full["weights"][c], c))
    rows = []
    for cap in (400, 1000, 2000):
        for mode in ("groups", "random"):
            sample, info = sample_records(records, cap, SEED, mode)
            s = summary(run(sample))
            diff, rho = compare(s, full)
            rows.append([cap, mode, s["n_rows"], info["groups_kept"], s["n_cand"], f"{diff:.4f}", f"{rho:.3f}"])
            print("small", cap, mode, diff, rho, flush=True)
    L = ["## customers.csv (4,000 rows), small caps", "",
         f"Reference: weights from all {len(records):,} rows. Max weight difference is the largest absolute "
         "difference in composite_weight over the columns kept in both runs; rank correlation is Spearman "
         "over the same columns.", ""]
    return L + table(["--max-rows", "Mode", "Rows analysed", "Groups kept", "Candidate pairs",
                      "Max weight diff", "Rank correlation"], rows) + [""]


def make_big() -> None:
    if BIG.is_file() and BIG_TRUTH.is_file():
        return
    generate_data.NUM_ENTITIES, generate_data.TOTAL_ROWS = 50_000, 100_000
    full = DATA / "customers_100k_full.csv"
    generate_data.main(output_path=full)
    split_truth.split_truth(full, "customer_id", DATA)


def pair_share(sampled_ids: set[str]) -> tuple[int, int]:
    truth = pd.read_csv(BIG_TRUTH, dtype=str)
    by_entity: dict[str, list[str]] = defaultdict(list)
    for rid, ent in zip(truth["customer_id"], truth["true_entity_id"]):
        by_entity[ent].append(rid)
    total = kept = 0
    for ids in by_entity.values():
        k = len(ids)
        total += k * (k - 1) // 2
        m = sum(i in sampled_ids for i in ids)
        kept += m * (m - 1) // 2
    return kept, total


def big_check() -> list[str]:
    make_big()
    import json
    runs = {}
    for label, extra in (("full (--max-rows 100000)", ["--max-rows", "100000"]),
                         (f"default cap ({DEFAULT_MAX_ROWS:,}), groups", []),
                         (f"default cap ({DEFAULT_MAX_ROWS:,}), random", ["--sample-mode", "random"])):
        out = ROOT / "out" / "group_sampling_100k" / label.split()[0] / (extra[-1] if extra else "groups")
        r = cli_run(BIG, out, extra)
        r["weights"] = {c: v["composite_weight"]
                        for c, v in json.loads((out / "rules.json").read_text(encoding="utf-8"))["columns"].items()}
        runs[label] = r
        print("big", label, r["seconds"], r["peak_mb"], flush=True)
    labels = list(runs)
    full = {"weights": runs[labels[0]]["weights"]}
    records = read_records(BIG)
    id_col = "customer_id"
    rows = []
    for label in labels:
        r = runs[label]
        if label == labels[0]:
            diff, rho, share = 0.0, 1.0, 1.0
            kept, total = pair_share({x[id_col] for x in records})
        else:
            diff, rho = compare({"weights": r["weights"]}, full)
            mode = "random" if "random" in label else "groups"
            sample, _ = sample_records(records, DEFAULT_MAX_ROWS, SEED, mode)
            kept, total = pair_share({x[id_col] for x in sample})
        rows.append([label, r["rows"], r["cands"], f"{r['seconds']:.1f}", f"{r['peak_mb']:.0f}",
                     f"{diff:.4f}", f"{rho:.3f}", f"{kept:,} of {total:,} ({kept / total:.1%})"])
    L = ["## customers_100k.csv (100,000 rows, 50,000 entities)", "",
         "Each run is `verity learn` in a fresh process, so time includes Python start and imports. Peak memory "
         "is the process peak working set. Weight difference and rank correlation compare each run with the "
         "full run. The last column is the share of true duplicate pairs (from the truth file, read here only) "
         "whose two rows are both in the analysed rows.", ""]
    return L + table(["Run", "Rows analysed", "Candidate pairs", "Seconds", "Peak memory (MB)",
                      "Max weight diff", "Rank correlation", "True duplicate pairs kept"], rows) + [""]


def main() -> int:
    L = ["# Group-aware row sampling", "",
         f"Seed {SEED}. Report only; nothing tuned. `groups` keeps rows that share a normalized value in a "
         "distinctive column together (groups of 2 to 50 rows); `random` draws rows uniformly.", ""]
    L += small_check()
    L += big_check()
    OUT.write_text("\n".join(L), encoding="utf-8")
    print("wrote", OUT)
    return 0


if __name__ == "__main__":
    sys.exit(main())
